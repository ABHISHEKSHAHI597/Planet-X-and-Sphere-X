"""Contract tooling (workflow.md §7.1, §7.3; owner P).

  python scripts/gen_contracts.py           write frontend/src/api/openapi.json and frontend/src/api/generated.ts
  python scripts/gen_contracts.py --check   exit 1 if either committed file is stale (CI "Contract" stage)

`app/schemas.py` is the authority; /openapi.json is derived from it; `generated.ts` is derived from
/openapi.json by the small deterministic generator below (no Node dependency). F's hand-written
`types.ts` keeps its names and doc comments; tests/app/test_contract.py fails if it declares a field the
schemas don't have. Switching imports from types.ts to generated.ts is F's call (docs/role-P-handoff.md)."""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
OUT_JSON = REPO / "frontend" / "src" / "api" / "openapi.json"
OUT_TS = REPO / "frontend" / "src" / "api" / "generated.ts"


def openapi() -> dict[str, Any]:
    sys.path.insert(0, str(REPO / "backend"))
    os.environ.setdefault("MOCK", "1")
    from app.main import create_app
    from app.settings import Settings
    s = Settings(environment="mock", mock=True, framesource="auto")
    return create_app(settings=s).openapi()  # type: ignore[no-any-return]


def dump(oa: dict[str, Any]) -> str:
    return json.dumps(oa, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def _ts(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return json.dumps(s["const"], ensure_ascii=False)
    if "enum" in s:
        return " | ".join(json.dumps(v, ensure_ascii=False) for v in s["enum"])
    for k in ("anyOf", "oneOf"):
        if k in s:
            return " | ".join(dict.fromkeys(_ts(x) for x in s[k]))
    t = s.get("type")
    if t == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(_ts(x) for x in s["prefixItems"]) + "]"
        inner = _ts(s.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        if "properties" in s:
            return _inline(s)
        ap = s.get("additionalProperties")
        return f"Record<string, {_ts(ap) if isinstance(ap, dict) else 'unknown'}>"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean",
            "null": "null"}.get(str(t), "unknown")


def _inline(s: dict[str, Any]) -> str:
    req = set(s.get("required", []))
    return "{ " + " ".join(f"{k}{'' if k in req else '?'}: {_ts(v)};" for k, v in s["properties"].items()) + " }"


def typescript(oa: dict[str, Any]) -> str:
    lines = ["/**", " * GENERATED by scripts/gen_contracts.py from the API's /openapi.json "
             f"(version {oa['info']['version']}). Do not edit.",
             " * Authority: backend/app/schemas.py (workflow.md §7.1). CI fails if this file is stale.", " */",
             f'export const API_VERSION = "{oa["info"]["version"]}";', ""]
    for name, s in sorted(oa["components"]["schemas"].items()):
        if s.get("type") == "object" and "properties" in s:
            req = set(s.get("required", []))
            lines.append(f"export interface {name} {{")
            for k, v in s["properties"].items():
                lines.append(f"  {k}{'' if k in req else '?'}: {_ts(v)};")
            lines.append("}")
        else:
            lines.append(f"export type {name} = {_ts(s)};")
        lines.append("")
    lines.append("export const API_PATHS = " + json.dumps(sorted(oa["paths"]), indent=2) + " as const;")
    return "\n".join(lines) + "\n"


def main() -> int:
    oa = openapi()
    want = {OUT_JSON: dump(oa), OUT_TS: typescript(oa)}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(REPO)) for p, txt in want.items()
                 if not p.exists() or p.read_text(encoding="utf-8") != txt]
        if stale:
            print("stale contract files (run python scripts/gen_contracts.py):", *stale, sep="\n  ")
            return 1
        print("contract files are fresh")
        return 0
    for p, txt in want.items():
        p.write_text(txt, encoding="utf-8", newline="\n")
        print("wrote", p.relative_to(REPO))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
