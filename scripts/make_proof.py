"""Generate the proof page data from the evidence records (optimisation.md VAL-2; advanced_research.md A4).

  python scripts/make_proof.py --write     regenerate frontend/src/content/proof.json and the README block
  python scripts/make_proof.py --check     exit 1 if either is out of date (CI)
  python scripts/make_proof.py             print the table

config/proof.yaml names, for each plain-language claim, the record and the metric that back it. Every number,
verdict, review state and staleness mark comes from `validation/` through scripts/validate.py, never from the
YAML: a claim cannot outrun its evidence (workflow.md §4.1). Run it after `validate.py status --write`."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import validate  # noqa: E402

SPEC = ROOT / "config" / "proof.yaml"
OUT_JSON = ROOT / "frontend" / "src" / "content" / "proof.json"
README = ROOT / "README.md"
BEGIN, END = "<!-- proof:begin (scripts/make_proof.py --write) -->", "<!-- proof:end -->"


def _fmt(value: Any, fmt: str | None) -> str:
    if fmt and isinstance(value, (int, float)) and not isinstance(value, bool):
        return fmt.format(value)
    return "—" if value is None else str(value)


def _ours(spec: dict[str, Any] | None, metrics: dict[str, Any]) -> str | None:
    if not spec:
        return None
    keys = [spec["metric"]] if "metric" in spec else list(spec["metrics"])
    missing = [k for k in keys if k not in metrics]
    if missing:
        raise SystemExit(f"config/proof.yaml: metric(s) {missing} are not in the record")
    if spec.get("reduce") == "passes":
        return f"{sum(1 for k in keys if metrics[k].get('pass') is True)} of {len(keys)}"
    vals = [metrics[k]["value"] for k in keys]
    value = {"max": max, "min": min}[spec["reduce"]](vals) if spec.get("reduce") else vals[0]
    return _fmt(value, spec.get("format"))


def _reference(spec: dict[str, Any] | None, metrics: dict[str, Any]) -> str | None:
    if not spec:
        return None
    if "threshold" in spec:
        return f"rule: {metrics[spec['threshold']]['threshold']}"
    return _fmt(metrics[spec["metric"]]["value"], spec.get("format"))


def _state(rec: validate.Rec) -> str:
    """One word a visitor can read; the UI explains each (frontend/src/components/ProofPage.tsx)."""
    verdict = rec.data["verdict"]
    if rec.review and rec.review.get("verdict") == "changes":
        return "changes requested"
    if verdict != "pass":
        return "failed" if verdict == "fail" else "inconclusive"
    if rec.stale:
        return "passed, re-run pending"
    return "accepted" if rec.reviewed else "passed, review pending"


def _row(item: dict[str, Any], recs: dict[str, validate.Rec], repo: str) -> dict[str, Any]:
    rec = recs.get(item["check"])
    if rec is None:
        raise SystemExit(f"config/proof.yaml: no record for check {item['check']!r}")
    metrics = rec.data.get("metrics") or {}
    path = rec.path.relative_to(validate.VAL).as_posix()
    return dict(
        id=item["id"], claim=item["claim"], detail=item["detail"], check=item["check"],
        ours=_ours(item.get("ours"), metrics), ours_label=item.get("ours_label"),
        reference=_reference(item.get("reference"), metrics),
        state=_state(rec), verdict=rec.data["verdict"], level=rec.level, date=rec.data["date"],
        record=path, record_url=f"{repo}/tree/main/validation/{path}",
    )


def build() -> dict[str, Any]:
    spec = yaml.safe_load(SPEC.read_text(encoding="utf-8"))
    recs = validate.latest(validate.load_records())
    rows = [_row(i, recs, spec["repo"]) for i in [*spec["claims"], *spec["open"]]]
    # The record decides where a row stands, not the YAML: a claim whose record fails, is inconclusive, or was sent
    # back by its reviewer is listed under "not proven yet" until a new record changes that.
    holds = lambda r: r["state"] == "accepted" or r["state"].startswith("passed")      # noqa: E731
    return dict(
        schema="parallax-proof@1",
        note="GENERATED by scripts/make_proof.py --write from validation/ records. Do not edit.",
        claims=[r for r in rows if holds(r)],
        open=[r for r in rows if not holds(r)],
    )


def markdown(data: dict[str, Any]) -> str:
    def table(rows: list[dict[str, Any]]) -> list[str]:
        out = ["| What we claim | Our number | Reference | State | Record |", "|---|---|---|---|---|"]
        for r in rows:
            out.append(f"| {r['claim']} | {r['ours'] or '—'} | {r['reference'] or '—'} | {r['state']} | "
                       f"[{r['check']}](validation/{r['record']}/report.md) ({r['level']}) |")
        return out
    lines = [BEGIN, "", *table(data["claims"]), "", "Not proven yet (each is hidden or marked *unvalidated* in the tool):",
             "", *table(data["open"]), "", END]
    return "\n".join(lines)


def readme_with(block: str) -> str:
    text = README.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(f"README.md needs the markers {BEGIN!r} and {END!r}")
    head, rest = text.split(BEGIN, 1)
    return head + block + rest.split(END, 1)[1]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    data = build()
    js = json.dumps(data, indent=1, ensure_ascii=False) + "\n"
    readme = readme_with(markdown(data))
    if a.write:
        OUT_JSON.write_text(js, encoding="utf-8")
        README.write_text(readme, encoding="utf-8")
        print(f"wrote {OUT_JSON.relative_to(ROOT)} and the README block: {len(data['claims'])} claims, {len(data['open'])} open")
        return 0
    if a.check:
        stale = [p.name for p, want in ((OUT_JSON, js), (README, readme))
                 if not p.exists() or p.read_text(encoding="utf-8") != want]
        if stale:
            print(f"out of date: {', '.join(stale)} (run: python scripts/make_proof.py --write)")
            return 1
        print("proof page data is fresh")
        return 0
    print(markdown(data))
    return 0


if __name__ == "__main__":
    sys.exit(main())
