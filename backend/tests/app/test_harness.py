def test_latest_orders_same_day_records_by_commit_not_by_sha_text(harness, tmp_path):
    """Same date, two commits: the record made on the descendant commit is the latest, even though its short sha
    sorts first as text: d6d2e45 → 3ae8487 is the real pair that showed the bug (F5 rerun ranked below the old record)."""
    v = harness
    old_sha = v.git("rev-parse", "--short=7", "d6d2e45")      # older commit
    new_sha = v.git("rev-parse", "--short=7", "3ae8487")      # its descendant
    if not old_sha or not new_sha:
        pytest.skip("git history not available")
    assert v._is_ancestor(old_sha, new_sha) is True and new_sha < old_sha   # text order is the wrong order
    recs = []
    for sha, name in ((new_sha, f"2026-11-08-{new_sha}"), (old_sha, f"2026-11-08-{old_sha}")):
        recs.append(v.Rec(tmp_path / "F5" / name, {"check_id": "F5", "date": "2026-11-08", "git_sha": sha}, None, False, ""))
    a, b = recs
    assert v.latest([a, b])["F5"] is a and v.latest([b, a])["F5"] is a
    # unknown commits fall back to the directory name
    x = v.Rec(tmp_path / "F5" / "2026-11-08-zzzzzzz", {"check_id": "F5", "date": "2026-11-08", "git_sha": "zzzzzzz"}, None, False, "")
    y = v.Rec(tmp_path / "F5" / "2026-11-08-aaaaaaa", {"check_id": "F5", "date": "2026-11-08", "git_sha": "aaaaaaa"}, None, False, "")
    assert v.latest([y, x])["F5"] is x
