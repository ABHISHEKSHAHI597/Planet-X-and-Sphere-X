"""L0 tests of P's evidence harness and flag guard (workflow.md §4.3–§4.5, §9.6, §11.2)."""
import importlib.util
import json
import sys
from pathlib import Path

import jsonschema
import pytest

REPO = Path(__file__).parents[3]
sys.path.insert(0, str(REPO / "scripts"))


def _mod(name):
    spec = importlib.util.spec_from_file_location(name, REPO / "scripts" / f"{name}.py")
    m = importlib.util.module_from_spec(spec)
    sys.modules[name] = m
    spec.loader.exec_module(m)
    return m


@pytest.fixture
def harness(tmp_path, monkeypatch):
    v = _mod("validate")
    monkeypatch.setattr(v, "VAL", tmp_path / "validation")
    return v


def _rec(v, tmp_path, check="G2-repro", verdict="pass", level="L3", author="P"):
    code = tmp_path / "code.py"
    if not code.exists():
        code.write_text("x = 1\n")
    return v.record(check, level, verdict, {"m": {"value": 1, "threshold": "1", "pass": verdict == "pass"}},
                    "report", ["input"], n_frames=3, code_paths=[str(code)], author=author), code


def test_record_schema_supersede_and_stale(harness, tmp_path):
    v = harness
    d, code = _rec(v, tmp_path)
    data = json.loads((d / "record.json").read_text())
    jsonschema.Draft202012Validator(json.loads((REPO / "validation/schema.json").read_text())).validate(data)
    assert data["schema"] == "parallax-evidence@1" and len(data["code_digest"]) == 64
    d2, _ = _rec(v, tmp_path, verdict="fail")                       # same day + sha → previous kept, renamed
    assert d2 == d and any("-superseded-1" in p.name for p in d.parent.iterdir())
    latest = v.latest(v.load_records())["G2-repro"]
    assert latest.data["verdict"] == "fail" and not latest.stale
    code.write_text("x = 2\n")                                       # code path changes → stale, one level lower
    latest = v.latest(v.load_records())["G2-repro"]
    assert latest.stale and latest.effective_level == "L2"


def test_review_rules(harness, tmp_path):
    v = harness
    d, _ = _rec(v, tmp_path)
    assert v.cmd_review(str(d), "P", "approve", "self review", False, "") == 2        # author cannot review
    assert v.cmd_review(str(d), "M", "approve", "wrong role", False, "") == 2         # registry says D reviews G2-repro
    assert v.cmd_review(str(d), "D", "approve", "reproduced", True, "") == 0
    r = v.latest(v.load_records())["G2-repro"]
    assert r.reviewed


def test_gate_needs_every_criterion_review_and_signoff(harness, tmp_path):
    v = harness
    reg = v.registry()
    d, _ = _rec(v, tmp_path)
    v.cmd_review(str(d), "D", "approve", "ok", True, "")
    cs = v.check_states(reg, v.latest(v.load_records()))
    assert cs["G2-repro"].accepted and cs["F2"].state == "open"
    gs = v.gate_states(reg, cs)
    g2 = gs["G2"]
    assert g2["state"] != "accepted" and "G1" in g2["requires_missing"]
    assert any(c["id"] == "G2.repro" and c["status"] == "met" for c in g2["criteria"])


